const { createRequire } = require('node:module');
const dependencies = process.env.FIREBASE_TEST_PACKAGE_JSON ? createRequire(process.env.FIREBASE_TEST_PACKAGE_JSON) : require;
const { initializeTestEnvironment, assertSucceeds, assertFails } = dependencies('@firebase/rules-unit-testing');
const { doc, setDoc, updateDoc, getDoc, deleteDoc } = dependencies('firebase/firestore');
(async () => {
 const env = await initializeTestEnvironment({ projectId: 'demo-audit', firestore: { host:'127.0.0.1', port:8088, rules:require('node:fs').readFileSync('firestore.rules','utf8') } });
 try {
 await env.clearFirestore();
 const alice=env.authenticatedContext('alice').firestore(), bob=env.authenticatedContext('bob').firestore(), guest=env.unauthenticatedContext().firestore();
 const poll={options:['a','b'],votes:{0:0,1:0},voters:[],voterChoices:{}};
 await env.withSecurityRulesDisabled(async c=>{
  const db=c.firestore();
  await setDoc(doc(db,'polls/p'),poll);
  await setDoc(doc(db,'fan_posts/p'),{userId:'alice',content:'test',likes:0,likedBy:[],poll});
  await setDoc(doc(db,'fan_posts/p/comments/c'),{userId:'alice',text:'test',likes:0,likedBy:[]});
  await setDoc(doc(db,'news/n'),{title:'News'});
 });
 await assertFails(updateDoc(doc(guest,'polls/p'),{votes:{0:1,1:0},voters:['alice'],voterChoices:{alice:0}}));
 await assertFails(updateDoc(doc(alice,'polls/p'),{votes:{0:100,1:0},voters:['alice'],voterChoices:{alice:0}}));
 await assertSucceeds(updateDoc(doc(alice,'polls/p'),{votes:{0:1,1:0},voters:['alice'],voterChoices:{alice:0}}));
 await assertFails(updateDoc(doc(alice,'polls/p'),{votes:{0:2,1:0}}));
 await assertSucceeds(updateDoc(doc(alice,'polls/p'),{votes:{0:0,1:1},voters:['alice'],voterChoices:{alice:1}}));
 await assertFails(updateDoc(doc(bob,'polls/p'),{votes:{0:1,1:0},voters:['alice'],voterChoices:{alice:0}}));
 await assertSucceeds(updateDoc(doc(bob,'fan_posts/p'),{poll:{...poll,votes:{0:1,1:0},voters:['bob'],voterChoices:{bob:0}}}));
 await assertFails(updateDoc(doc(bob,'fan_posts/p'),{poll:{...poll,options:['changed'],votes:{0:1},voters:['bob'],voterChoices:{bob:0}}}));
 await assertSucceeds(updateDoc(doc(bob,'fan_posts/p/comments/c'),{likes:1,likedBy:['bob']}));
 await assertFails(updateDoc(doc(alice,'fan_posts/p/comments/c'),{likes:1,likedBy:['alice']}));
 await assertSucceeds(updateDoc(doc(guest,'news/n'),{views:1}));
 await assertFails(updateDoc(doc(guest,'news/n'),{views:100}));
 const attendance={matchId:'m',votes:{yes:1,no:0,maybe:0},voters:{alice:'yes'}};
 await assertFails(setDoc(doc(alice,'match_day_attendance/attendance_m'),{...attendance,votes:{yes:100,no:0,maybe:0}}));
 await assertSucceeds(setDoc(doc(alice,'match_day_attendance/attendance_m'),attendance));
 await assertSucceeds(updateDoc(doc(alice,'match_day_attendance/attendance_m'),{votes:{yes:0,no:1,maybe:0},voters:{alice:'no'}}));
 await assertFails(updateDoc(doc(bob,'match_day_attendance/attendance_m'),{voters:{alice:'yes'}}));
 const profile={name:'Alice',email:'alice@example.com',role:'user',tier:'new'};
 await assertFails(setDoc(doc(alice,'users/alice'),{...profile,tier:'royal'}));
 await assertFails(setDoc(doc(alice,'users/alice'),{...profile,isVerified:true}));
 await assertFails(setDoc(doc(alice,'users/alice'),{...profile,uid:'bob'}));
 await assertSucceeds(setDoc(doc(alice,'users/alice'),profile));
 await assertSucceeds(updateDoc(doc(alice,'users/alice'),{name:'Alice Updated'}));
 await assertFails(updateDoc(doc(alice,'users/alice'),{tier:'royal'}));
 await assertFails(updateDoc(doc(alice,'users/alice'),{uid:'bob'}));
 const metadata={name:'image',ownerId:'alice',contentType:'image/png',size:3,chunksCount:1,data:'YWJj',updatedAt:'today'};
 await assertSucceeds(setDoc(doc(alice,'app_images/image'),metadata));
 await assertFails(setDoc(doc(guest,'app_images/guest'),metadata));
 await assertFails(updateDoc(doc(bob,'app_images/image'),{ownerId:'bob'}));
 await assertFails(setDoc(doc(bob,'app_images/image/chunks/0'),{index:0,data:'YWJj'}));
 await assertSucceeds(setDoc(doc(alice,'app_images/image/chunks/0'),{index:0,data:'YWJj'}));
 await assertFails(setDoc(doc(alice,'app_images/image/chunks/1000'),{index:1000,data:'YWJj'}));
 await assertFails(getDoc(doc(guest,'users/alice')));
 await assertFails(getDoc(doc(bob,'users/alice')));
 await assertSucceeds(getDoc(doc(alice,'users/alice')));
 await assertFails(updateDoc(doc(alice,'users/alice'),{'stats.ittihadawyScore':999999}));
 await assertFails(setDoc(doc(bob,'users/bob'),{...profile,stats:{ittihadawyScore:1}}));
 const member={groupId:'g',userId:'alice',userName:'Alice',userRole:'member'};
 await assertSucceeds(setDoc(doc(alice,'world_group_members/g_alice'),member));
 await assertFails(getDoc(doc(guest,'world_group_members/g_alice')));
 await assertFails(setDoc(doc(bob,'world_group_members/g_alice'),{...member,userId:'bob'}));
 await assertFails(updateDoc(doc(alice,'world_group_members/g_alice'),{role:'group_admin'}));
 await assertFails(deleteDoc(doc(bob,'world_group_members/g_alice')));
 const post={authorId:'alice',content:'test',likes:0,likedBy:[],comments:[],commentsCount:0,pinned:false};
 await assertSucceeds(setDoc(doc(alice,'world_posts/w'),post));
 await assertFails(updateDoc(doc(bob,'world_posts/w'),{pinned:true}));
 await assertFails(updateDoc(doc(bob,'world_posts/w'),{authorId:'bob',content:'hijack'}));
 const comment={id:'c',userId:'bob',content:'hello'};
 await assertSucceeds(updateDoc(doc(bob,'world_posts/w'),{comments:[comment],commentsCount:1}));
 await assertFails(updateDoc(doc(alice,'world_posts/w'),{comments:[{...comment,content:'forged'}],commentsCount:1}));
 await assertFails(updateDoc(doc(alice,'world_posts/w'),{comments:[],commentsCount:0}));
 await assertSucceeds(updateDoc(doc(bob,'world_posts/w'),{comments:[],commentsCount:0}));
 const event={authorId:'alice',title:'meet',participantsCount:1,participantUids:['alice']};
 await assertSucceeds(setDoc(doc(alice,'world_events/e'),event));
 await assertFails(updateDoc(doc(bob,'world_events/e'),{title:'hijacked'}));
 await assertSucceeds(updateDoc(doc(bob,'world_events/e'),{participantsCount:2,participantUids:['alice','bob']}));
 await assertFails(updateDoc(doc(bob,'world_events/e'),{participantsCount:1,participantUids:['bob']}));
 console.log('Firestore authorization regressions passed');
 } finally { await env.cleanup(); }
})().catch(e=>{console.error(e);process.exitCode=1});
